import ts from 'typescript';
import {readFileSync,writeFileSync} from 'node:fs';
import {build} from 'esbuild';
// Compile the actual online grading engine; never maintain a second grading formula.
const source=['src/lib/grading/deped.ts','src/lib/grading/presets.ts'].map(path=>ts.transpileModule(readFileSync(path,'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText).join('\n');
writeFileSync('public/offline-grading.js','// Generated by scripts/build-offline.mjs. Edit src/lib/grading instead.\n'+source);
await build({entryPoints:['src/features/report-card-generation/offline-report.ts'],outfile:'public/offline-report-engine.js',bundle:true,format:'esm',platform:'browser',target:'es2022',minify:true,legalComments:'eof'});
